package mcp

import (
	"context"
	"encoding/json"
	"fmt"
	"log"
	"os"
	"time"

	"github.com/mark3labs/mcp-go/mcp"
	"github.com/mark3labs/mcp-go/server"
	"taskflow/internal/domain"
	"taskflow/internal/repository"
)

const PendingTasksResourceURI = "tasks://pending-for-ai"

// AvailableTaskDTO defines the output format for list_available_tasks (SPEC-001 §4.2.1).
type AvailableTaskDTO struct {
	ID          int64     `json:"id"`
	Title       string    `json:"title"`
	Description string    `json:"description"`
	Tags        []string  `json:"tags"`
	CreatedAt   time.Time `json:"created_at"`
}

// Server wraps the MCPServer and the SQLite TaskRepository.
type Server struct {
	repo      *repository.TaskRepository
	mcpServer *server.MCPServer
}

// NewServer constructs and configures the taskflow MCP server with its resource and 4 tools.
func NewServer(repo *repository.TaskRepository) *Server {
	s := server.NewMCPServer(
		"taskflow",
		"1.0.0",
		server.WithResourceCapabilities(false, false),
		server.WithToolCapabilities(false),
	)

	srv := &Server{
		repo:      repo,
		mcpServer: s,
	}
	srv.registerResources()
	srv.registerTools()
	return srv
}

// MCPServer returns the underlying *server.MCPServer instance.
func (s *Server) MCPServer() *server.MCPServer {
	return s.mcpServer
}

// ServeStdio runs the MCP server over stdin/stdout while forcing all error logging to stderr.
func (s *Server) ServeStdio() error {
	log.SetOutput(os.Stderr)
	errLogger := log.New(os.Stderr, "[taskflow-mcp] ", log.LstdFlags)
	return server.ServeStdio(s.mcpServer, server.WithErrorLogger(errLogger))
}

func (s *Server) registerResources() {
	res := mcp.NewResource(
		PendingTasksResourceURI,
		"Pending Tasks for AI",
		mcp.WithMIMEType("application/json"),
		mcp.WithResourceDescription("Returns all tasks where status = 'pending' and delegable_to_ai = 1"),
	)
	s.mcpServer.AddResource(res, s.handleReadPendingResource)
}

func (s *Server) registerTools() {
	// 1. list_available_tasks
	listTool := mcp.NewTool(
		"list_available_tasks",
		mcp.WithDescription("Lists pending tasks delegable to AI, optionally filtered by tag."),
		mcp.WithString("tag_filter", mcp.Description("Optional tag to filter tasks")),
	)
	s.mcpServer.AddTool(listTool, s.handleListAvailableTasks)

	// 2. claim_task
	claimTool := mcp.NewTool(
		"claim_task",
		mcp.WithDescription("Atomically claims a pending AI-delegable task and transitions it to in_progress."),
		mcp.WithNumber("task_id", mcp.Required(), mcp.Description("ID of the task to claim")),
		mcp.WithString("agent_name", mcp.Required(), mcp.Description("Identifier of the AI agent claiming the task")),
	)
	s.mcpServer.AddTool(claimTool, s.handleClaimTask)

	// 3. submit_task_result
	submitTool := mcp.NewTool(
		"submit_task_result",
		mcp.WithDescription("Submits the result notes for an in_progress task and transitions it to review or done."),
		mcp.WithNumber("task_id", mcp.Required(), mcp.Description("ID of the in_progress task")),
		mcp.WithString("ai_notes", mcp.Required(), mcp.Description("Resolution notes generated by the AI agent")),
		mcp.WithBoolean("requires_review", mcp.Required(), mcp.Description("If true, moves status to 'review'; if false, moves status to 'done'")),
	)
	s.mcpServer.AddTool(submitTool, s.handleSubmitTaskResult)

	// 4. create_subtask
	createSubtaskTool := mcp.NewTool(
		"create_subtask",
		mcp.WithDescription("Creates a new task in pending status and returns its created ID."),
		mcp.WithString("title", mcp.Required(), mcp.Description("Title of the subtask")),
		mcp.WithString("description", mcp.Description("Detailed description of the subtask")),
		mcp.WithBoolean("delegable_to_ai", mcp.Required(), mcp.Description("Whether this subtask can be claimed by AI agents")),
		mcp.WithArray("tags", mcp.Description("List of string tags"), mcp.WithStringItems()),
	)
	s.mcpServer.AddTool(createSubtaskTool, s.handleCreateSubtask)
}

func (s *Server) handleReadPendingResource(ctx context.Context, request mcp.ReadResourceRequest) ([]mcp.ResourceContents, error) {
	tasks, err := s.repo.ListAvailableForAI(ctx, "")
	if err != nil {
		return nil, fmt.Errorf("read pending tasks resource: %w", err)
	}
	if tasks == nil {
		tasks = []domain.Task{}
	}
	data, err := json.Marshal(tasks)
	if err != nil {
		return nil, fmt.Errorf("marshal pending tasks: %w", err)
	}

	uri := request.Params.URI
	if uri == "" {
		uri = PendingTasksResourceURI
	}

	return []mcp.ResourceContents{
		mcp.TextResourceContents{
			URI:      uri,
			MIMEType: "application/json",
			Text:     string(data),
		},
	}, nil
}

func (s *Server) handleListAvailableTasks(ctx context.Context, request mcp.CallToolRequest) (*mcp.CallToolResult, error) {
	tagFilter := mcp.ParseString(request, "tag_filter", "")
	tasks, err := s.repo.ListAvailableForAI(ctx, tagFilter)
	if err != nil {
		return mcp.NewToolResultError(fmt.Sprintf("failed to list available tasks: %v", err)), nil
	}

	dtos := make([]AvailableTaskDTO, 0, len(tasks))
	for _, t := range tasks {
		tags := t.Tags
		if tags == nil {
			tags = []string{}
		}
		dtos = append(dtos, AvailableTaskDTO{
			ID:          t.ID,
			Title:       t.Title,
			Description: t.Description,
			Tags:        tags,
			CreatedAt:   t.CreatedAt,
		})
	}

	payload, err := json.Marshal(dtos)
	if err != nil {
		return mcp.NewToolResultError(fmt.Sprintf("failed to serialize tasks: %v", err)), nil
	}
	return mcp.NewToolResultText(string(payload)), nil
}

func (s *Server) handleClaimTask(ctx context.Context, request mcp.CallToolRequest) (*mcp.CallToolResult, error) {
	taskID := mcp.ParseInt64(request, "task_id", 0)
	agentName := mcp.ParseString(request, "agent_name", "")

	if taskID <= 0 {
		return mcp.NewToolResultError("task_id must be a positive integer"), nil
	}
	if agentName == "" {
		return mcp.NewToolResultError("agent_name is required"), nil
	}

	if err := s.repo.ClaimTask(ctx, taskID, agentName); err != nil {
		return mcp.NewToolResultError(fmt.Sprintf("cannot claim task %d: %v", taskID, err)), nil
	}

	resp, _ := json.Marshal(map[string]any{
		"task_id":        taskID,
		"status":         domain.StatusInProgress,
		"assigned_agent": agentName,
	})
	return mcp.NewToolResultText(string(resp)), nil
}

func (s *Server) handleSubmitTaskResult(ctx context.Context, request mcp.CallToolRequest) (*mcp.CallToolResult, error) {
	taskID := mcp.ParseInt64(request, "task_id", 0)
	aiNotes := mcp.ParseString(request, "ai_notes", "")
	requiresReview := mcp.ParseBoolean(request, "requires_review", true)

	if taskID <= 0 {
		return mcp.NewToolResultError("task_id must be a positive integer"), nil
	}

	if err := s.repo.SubmitTaskResult(ctx, taskID, aiNotes, requiresReview); err != nil {
		return mcp.NewToolResultError(fmt.Sprintf("cannot submit result for task %d: %v", taskID, err)), nil
	}

	newStatus := domain.StatusDone
	if requiresReview {
		newStatus = domain.StatusReview
	}
	resp, _ := json.Marshal(map[string]any{
		"task_id": taskID,
		"status":  newStatus,
	})
	return mcp.NewToolResultText(string(resp)), nil
}

func (s *Server) handleCreateSubtask(ctx context.Context, request mcp.CallToolRequest) (*mcp.CallToolResult, error) {
	title := mcp.ParseString(request, "title", "")
	description := mcp.ParseString(request, "description", "")
	delegableToAI := mcp.ParseBoolean(request, "delegable_to_ai", true)

	var tags []string
	rawTags := mcp.ParseArgument(request, "tags", nil)
	switch v := rawTags.(type) {
	case []string:
		tags = v
	case []any:
		for _, item := range v {
			if str, ok := item.(string); ok {
				tags = append(tags, str)
			}
		}
	}

	task := &domain.Task{
		Title:         title,
		Description:   description,
		Status:        domain.StatusPending,
		DelegableToAI: delegableToAI,
		Tags:          tags,
	}

	id, err := s.repo.Create(ctx, task)
	if err != nil {
		return mcp.NewToolResultError(fmt.Sprintf("failed to create subtask: %v", err)), nil
	}

	resp, _ := json.Marshal(map[string]any{
		"id":     id,
		"status": domain.StatusPending,
	})
	return mcp.NewToolResultText(string(resp)), nil
}
